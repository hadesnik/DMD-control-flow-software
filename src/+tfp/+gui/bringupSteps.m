function steps = bringupSteps()
%bringupSteps The guided bringup procedure, as data.
%
%   steps = tfp.gui.bringupSteps()
%
%   ONE declarative entry per section of docs/BRINGUP_GUIDE.md sections 1-7,
%   in the order they must be done. This is the script the guided wizard
%   reads out loud: what to do at the bench, what the software is about to
%   do, what a good result looks like, and what to change when it is not.
%
%   WHY THIS IS DATA AND NOT CODE. The wizard has to (a) show the whole
%   procedure before any of it has run, (b) know what is blocked by what,
%   and (c) explain a failure in the same words whether it happened in the
%   GUI or at the command line. A list of buttons with instructions buried
%   in their callbacks can do none of those. Keeping it declarative also
%   means the acceptance thresholds are all visible in one file and can be
%   diffed when someone changes one.
%
%   No graphics, no hardware, no arithmetic — tfp.gui.stepMetrics derives
%   the quantities the criteria test, and tfp.gui.stepVerdict applies them.
%   All three run under matlab -nodisplay and are covered by
%   tests/test_bringup_steps.m.
%
%   FIELDS OF ONE STEP
%     .id        char slug, stable — results and report sections key on it
%     .section   the docs/BRINGUP_GUIDE.md section number this implements
%     .title     one short line for the step rail
%     .purpose   one sentence: what this measures and why it must be done
%     .kind      'checklist' (operator confirms) | 'measure' (software acts)
%     .requires  step ids that must have passed first
%     .needs     device keys the session must have real, before it may run
%     .setup     cellstr — what to do PHYSICALLY, before pressing Proceed
%     .willDo    cellstr — what the software will do when you press Proceed
%     .hazard    char — the safety sentence for this step, '' if none
%     .checks    cellstr — checklist items ('checklist' steps only)
%     .method    CalibrationSession method to call ('measure' steps only)
%     .knobs     struct array of operator-settable options (see knob())
%     .saveKind  tfp.io.saveCalibration slug, '' for steps that save nothing
%     .criteria  struct array of acceptance tests (see crit())
%     .remedy    cellstr — what to change on the bench when it does not pass
%     .records   cellstr — the numbers to write on the record sheet (section 11)
%     .plot      recipe name the view renders; 'none' for checklist steps
%
%   See also tfp.gui.stepVerdict, tfp.gui.stepMetrics,
%   tfp.gui.CalibrationSession/runStep, docs/BRINGUP_GUIDE.md.

steps = emptyStep();

% =========================================================================
% Section 1 - prerequisites. Nothing here touches the rig; both steps exist
% because every downstream number is wrong in a way that still looks
% self-consistent if the bench is not what the handoff says it is.
% =========================================================================

s          = newStep('prereq_bench', '1', 'Bench prerequisites');
s.purpose  = ['Confirm the arm on the table is the arm the handoff describes. ' ...
              'Every scale constant downstream is computed for one specific ' ...
              'prescription, and a half-done lens swap looks self-consistent ' ...
              'while being wrong by a fixed factor.'];
s.kind     = 'checklist';
s.setup    = { ...
    'Nothing is powered for this step - it is a walk along the bench with the handoff open.'
    'Open docs/optics_handoff.md and read the "build_label" line at the top of the constants block.'
    'Check each lens seat against that label, not against memory.'};
s.checks   = { ...
    'Ra = 250 mm and Rb = 200 mm in the pre-grating relay (rev 5 moved Ra from 300 - check the SEAT, not just f7)'
    'f7 = 300 mm confirmed in its seat (bench-confirmed 2026-08-19)'
    'f6 = 80 mm confirmed installed (bench of record carried 150 mm - this is the swap the f7 confirmation did NOT cover)'
    'Grating incidence re-set to 43.7 deg in / 33.7 deg out (rev 5 re-angled it from 42.8/34.5)'
    '3D-SHOT zero-order block at I1 REMOVED (it shadows the middle of the merged field)'
    'DMD chip Scheimpflug tilt set - sign is OPPOSITE the old bring-up-arm instructions'
    'Half-wave plate + polarizer set for s-pol on the grating'
    'Beam expander identity recorded (custom 1.75x vs GBE02-B changes the dwell-correction table)'
    'Thin fluorescent film slide at the rig (lateral and z calibration)'
    'Thick fluorescent slab at the rig (section 7 burn/bleach verify)'};
s.remedy   = { ...
    'Any unchecked box stops the run here rather than propagating a silent scale error.'
    'If a lens differs from the handoff, do not adjust the software: change the model in the'
    'optics repo, regenerate docs/optics_handoff.md, and commit it here. The handoff is the'
    'authority and this repo reads it at runtime.'
    'The two-lens trap: Ra 300->250 and f7 250->300 are both ratios of 1.2 and they enter the'
    'scale inversely, so correcting only one leaves every internal consistency check passing'
    'and the groove scale wrong by 1.2x.'};
s.records  = {'build_label from the handoff constants block'
              'Beam expander identity (custom 1.75x or catalogue GBE)'};
steps(end+1) = s;

s          = newStep('prereq_software', '1', 'Software and device preflight');
s.purpose  = ['Interrogate every instrument this session will drive, and say ' ...
              'which ones answered. A device that is silently simulated is how ' ...
              'a session produces confident numbers about hardware that was ' ...
              'never there.'];
s.kind     = 'measure';
s.method   = 'preflight';
s.setup    = { ...
    'Repo cloned and up to date on all three PCs, with addpath(''src'') done in each MATLAB.'
    'msocket library on the path of all three (the msocketPath config keys).'
    'On the imaging PC, inside the ScanImage MATLAB: addpath(''<repo>/scripts/imaging_pc_setup'');'
    '  si_calib_helper  (port 3048 - the z ruler AND ScanImage control; set zstage.relay_port: 3048)'
    '  or si_motor_helper (port 3047 - the z ruler only). Run ONE: a MATLAB holds one accept loop.'
    'On the SLM PC: cd <repo>; addpath(''src''); addpath(''scripts/slm_pc_setup''); slm_server'
    'configs/real.yaml reviewed - slm.host, zstage, etl, threeD, laser.carbide_modulator_ao_channel.'};
s.willDo   = { ...
    'Ask the DMD, DAQ, camera and z ruler to identify themselves and answer a round trip.'
    'Report whether the CARBIDE modulator is wired, whether the PM100D driver is present,'
    'and whether the ScanImage link is configured.'
    'Name every device that fell back to a simulator.'};
s.criteria = [ ...
    crit('m.nFailed', 'Devices that failed to answer', '', 'eq', 0, 'fail', ...
         'A device that cannot be reached cannot be calibrated. Fix it before measuring.') ...
    crit('m.nUnexpectedlySimulated', 'Devices that fell back to a simulator', '', 'eq', 0, 'adjust', ...
         ['A device that was asked for by name and could not be built is now a simulator, and ' ...
          'nothing measured against it is a calibration. The MATLAB console carries the original ' ...
          'construction error, which is the real diagnosis.']) ...
    crit('m.nSimulatedRows', 'Devices declared simulated', '', 'eq', 0, 'warn', ...
         'Expected on a mock session, where the whole rig is simulated on purpose and says so.') ...
    crit('m.nPending', 'Devices not yet configured', '', 'eq', 0, 'warn', ...
         'Pending is not broken - it usually means the laser state has not been entered yet.')];
s.remedy   = { ...
    'Work the "What to do" column of the preflight table top to bottom; it names the fix per device.'
    'A simulated device is a construction failure that was caught and substituted - the warning in'
    'the MATLAB console carries the original error message, which is the real diagnosis.'};
s.plot     = 'preflight';
steps(end+1) = s;

% =========================================================================
% Section 2 - the SLM link. Before any light: this is a network handshake.
% =========================================================================

s          = newStep('slm_link', '2', 'SLM PC link');
s.purpose  = ['Prove the DAQ PC can drive the Meadowlark through the SLM PC ' ...
              'before anything depends on it. The DAQ PC never sends pixels - ' ...
              'it sends a small mask spec and the SLM PC recomputes identical ' ...
              'masks with the same engine.'];
s.kind     = 'measure';
s.method   = 'runSlmLinkCheck';
s.needs    = {'slm'};
s.setup    = { ...
    'Work through docs/blink-api-audit.md on the SLM PC first - the load-bearing question is'
    'whether this unit does onboard-sequence memory with external-trigger advance, which decides'
    'slm.trigger_mode (''ttl'' if yes, ''software'' permanently if no).'
    'Edit scripts/slm_pc_setup/slm_pc_config.m: port 3046, DLL / header / LUT paths.'
    'Leave dryRun = true for the first link test - no hardware is touched in dry run.'
    'Start the server and leave it running: slm_server (it listens until SHUTDOWN or Ctrl-C).'
    'Once the dry run passes, set dryRun = false, restart slm_server, and run this step again.'};
s.willDo   = { ...
    'Connect to the SLM PC on port 3046.'
    'Build the defocus system from the config and prepare a three-mask sequence (-20, 0, +20 um).'
    'Expect READY back, then blank the device and expect BLANK_OK.'
    'Leave the SLM blanked - a flat mask is the safe state.'};
s.criteria = [ ...
    crit('connected',  'msocket link to the SLM PC', '', 'isTrue', true, 'fail', ...
         'Without the link nothing axial can be calibrated or run.') ...
    crit('readyOk',    'READY handshake on a prepared sequence', '', 'isTrue', true, 'fail', ...
         'READY is the server confirming it recomputed the same masks from the spec.') ...
    crit('blankOk',    'BLANK acknowledged', '', 'isTrue', true, 'fail', ...
         'Blank is the walk-away state; if it does not work, the device cannot be left safe.') ...
    crit('dryRun',     'Server still in dryRun', '', 'isFalse', false, 'warn', ...
         'A dry run proves the protocol, not the upload. Repeat with dryRun = false before trusting it.')];
s.remedy   = { ...
    'tfp:hardware:MeadowlarkSLM:replyTimeout - slm_server is not running, slm.host is wrong, or a'
    'firewall is in the way. The server prints every command it receives, so look at its console first.'
    'tfp:hardware:BlinkSLM:sdkNotVendored - the Blink audit is not done. The server runs dry until'
    'the header is vendored in vendor/meadowlark/official/ and audited. Never invent a Blink'
    'function name to get past this.'
    'Record the decided trigger_mode in configs/real.yaml before moving on.'};
s.records  = {'slm.trigger_mode decided (ttl or software)'
              'Blink SDK version and DLL path'};
s.plot     = 'none';
steps(end+1) = s;

% =========================================================================
% Laser state. Not a section of its own in the guide, but nothing that puts
% light on the sample may run before it: the pulse-energy interlock is
% fail-closed on rep rate.
% =========================================================================

s          = newStep('laser_state', '0', 'Laser state');
s.purpose  = ['Tell the interlock what the laser is actually doing. Believing ' ...
              '100 kHz while the pulse picker sits at /100 understates pulse ' ...
              'energy a hundredfold, so every light-emitting step is blocked ' ...
              'until this is entered.'];
s.kind     = 'measure';
s.method   = 'applyLaserState';
s.setup    = { ...
    'Read the values off the CARBIDE control software on the Holo PC - do not recall them.'
    'Enter the FRONT-PANEL AVERAGE POWER if you can see it. That is a laser-plane number, so the'
    'interlock needs no arm-transmission assumption; without it the interlock scales a sample-plane'
    'power up by the unmeasured 0.182 and warns on every call.'
    'Note the pulse-picker division. This is the single most dangerous field on the form.'};
s.willDo   = { ...
    'Adopt the state, compute the effective rep rate, and stamp it into every calibration saved'
    'for the rest of this session.'
    'Enable the steps that emit light.'};
s.knobs    = [ ...
    knob('repRateKhz',          'Base rep rate',            100,  'kHz', 'CARBIDE base rate BEFORE the pulse picker.') ...
    knob('pulsePickerDivision', 'Pulse-picker division',      1,  '',    'A wrong division mis-scales every pulse-energy check.') ...
    knob('frontPanelPowerW',    'Front-panel average power',  0,  'W',   'PREFERRED interlock input. 0 = not entered.') ...
    knob('frontPanelSetpointNm','Front-panel setpoint',    1030,  'nm',  'Certificate s/n C264570 measures 1038; both are recorded.')];
s.criteria = [ ...
    crit('effectiveRepRateHz', 'Effective rep rate', 'Hz', 'gt', 0, 'fail', ...
         'The interlock divides average power by this to get pulse energy.') ...
    crit('m.hasFrontPanelPower', 'Front-panel power entered', '', 'isTrue', true, 'warn', ...
         'Without it every interlock call assumes the unmeasured 0.182 arm transmission and warns.')];
s.remedy   = { ...
    'If the front-panel power is unknown, the session still runs - it will warn'
    'tfp:util:assertPulseEnergySafe:armTransmissionAssumed on every light-emitting call.'
    'Measuring laser head -> sample transmission and recording laser.arm_transmission retires that warning.'};
s.plot     = 'none';
steps(end+1) = s;

% =========================================================================
% Section 3 - power. The first step that emits light.
% =========================================================================

s          = newStep('power_curve', '3', 'Volts to mW');
s.purpose  = ['Calibrate the CARBIDE modulator against the power meter so ' ...
              'every later step can ask for milliwatts instead of volts, and ' ...
              'so the interlock knows what a commanded voltage means.'];
s.kind     = 'measure';
s.method   = 'runPowerSweep';
s.requires = {'laser_state'};
s.needs    = {'laser', 'laserState'};
s.hazard   = ['This step ramps the modulator to the ceiling you authorise. ' ...
              'Consent is taken ONCE for the whole ramp - a dialog per step ' ...
              'would train you to click through them - but the hard interlock ' ...
              'still runs on every single step.'];
s.setup    = { ...
    'Wire the CARBIDE external modulator to its DAQ AO channel. Record terminal, cable, voltage'
    'range and POLARITY in docs/WIRING.md, then set laser.carbide_modulator_ao_channel.'
    'VERIFY ON A METER THAT 0 V MEANS OFF before the beam is connected. Every zero-on-error path'
    'in this software assumes it, including the BEAM OFF button.'
    'Put the Thorlabs PM100D head at the SAMPLE PLANE and set its wavelength to 1038 nm.'
    'Clear the beam path of anything that should not see full power.'};
s.willDo   = { ...
    'Ask once for the ramp ceiling, then step the modulator from Start to End.'
    'At each step: settle, average several meter readings, and record the standard deviation.'
    'Fit the curve, load it into the laser controller, and report where the working powers sit.'
    'Return the modulator to zero at the end.'};
s.knobs    = [ ...
    knob('vMin',        'Start',           0, 'V', 'Begin at zero so the 0 V = off check is real.') ...
    knob('vMax',        'End',             5, 'V', 'The ramp ceiling you will be asked to authorise.') ...
    knob('nSteps',      'Steps',          21, '',  'More steps resolve a non-linear modulator response.') ...
    knob('settleTimeS', 'Settle per step', 5, 's', 'The meter head is thermal; too short reads low and drifting.') ...
    knob('nAverages',   'Readings/step',   5, '',  'The spread across these is the error bar on the curve.')];
s.saveKind = 'power_curve';
s.criteria = [ ...
    crit('m.zeroIsOff',      'Power at 0 V is off',      '',  'isTrue', true, 'fail', ...
         ['The open safety question in CLAUDE.md, answered by measurement: if 0 V is not off, ' ...
          'every zero-on-error path drives the laser the WRONG WAY. Nothing else may run.']) ...
    crit('m.monotonic',      'Curve is monotonic',        '',  'isTrue', true, 'adjust', ...
         'A non-monotonic curve cannot be inverted, so voltsForMw would be ambiguous.') ...
    crit('m.maxPowerMw',     'Maximum power reached',     'mW','gt',  1,    'fail', ...
         'Essentially no power at the sample means the beam is blocked, misaligned, or the shutter is closed.') ...
    crit('m.worstStdFrac',   'Worst reading scatter',     '',  'lt',  0.05, 'warn', ...
         'Scatter over 5 percent of the reading usually means the settle time is too short.') ...
    crit('m.hasWorkingPoint','5 mW is inside the range',  '',  'isTrue', true, 'warn', ...
         '5 mW is the calibration working power for every later step; it must be on the dial.')];
s.remedy   = { ...
    'Power at 0 V not off: STOP. Check the modulator polarity on a meter and fix the wiring or the'
    'controller''s voltage_min before anything else. This is not a software setting to work around.'
    'No power at all: shutter closed, beam blocked, wrong AO terminal, or the modulator BNC is on'
    'the wrong input. The DAQ log shows the voltage that was actually commanded.'
    'Non-monotonic or noisy: increase Settle per step; the S350C head has a thermal time constant'
    'of seconds, not milliseconds.'};
s.records  = {'Maximum power at the sample (mW)'
              'Voltage that gives 5 mW (calibration working power)'
              'Voltage that gives 42 mW (the SLM alignment cap - know where it is on the dial)'};
s.plot     = 'powerCurve';
steps(end+1) = s;

% =========================================================================
% Section 4 - lateral calibration, four gated sub-steps.
% =========================================================================

s          = newStep('lateral_dmd_camera', '4a', 'DMD to camera affine');
s.purpose  = ['Fit the transform from DMD pixels to substage-camera pixels ' ...
              'by projecting a grid of spots and finding where each one lands. ' ...
              'This is the measurement that makes targeting possible at all.'];
s.kind     = 'measure';
s.method   = 'runDmdToCamera';
s.requires = {'power_curve'};
s.needs    = {'dmd', 'camera', 'laserState'};
s.hazard   = 'Single small spots at calibration power - far under every cap.';
s.setup    = { ...
    'Put the THIN fluorescent film slide on the stage.'
    'Turn on the substage Basler and focus it on the film. Use the Camera tab: raise exposure until'
    'the spot is bright, then back off until "Mark saturation" shows no red - a clipped plateau'
    'silently degrades every centroid.'
    'Capture a dark frame with the beam off (Camera tab) so the background pedestal is subtracted.'
    'If you are on the section 5 Option B sample mount: do NOT move XY from here until 4c is done.'};
s.willDo   = { ...
    'Project a grid of single spots across the usable patch, one at a time.'
    'Snap the camera at each, find the spot centroid, and least-squares fit a 2D affine.'
    'Report the residual per point, so a single bad point is visible rather than averaged away.'};
s.knobs    = [ ...
    knob('gridSize',     'Grid points per side', 5, '',  'Five per side is 25 points - enough to see structure in the residuals.') ...
    knob('spotRadiusPx', 'Spot radius',          8, 'px','Bigger is brighter and easier to centroid; smaller is more precise.') ...
    knob('powerMw',      'Power',                5, 'mW','The calibration working power.')];
s.criteria = [ ...
    crit('residualErrorPx',    'Affine residual (RMS)',   'camera px', 'lt', 1,  'adjust', ...
         'Under one camera pixel is the bar in the guide. Above it, the fit is describing something that moved.') ...
    crit('nCalibrationPoints', 'Points that fitted',      '',          'gt', 8,  'fail', ...
         'Too few surviving points and the affine is under-determined however small its residual looks.') ...
    crit('m.scaleAgreesWithHandoff', 'Scale matches the handoff', '',  'isTrue', true, 'warn', ...
         ['Guide section 4: disagreement of more than a few percent means something is installed ' ...
          'differently. The measurement is still the calibration - this is a pointer to the bench.'])];
s.remedy   = { ...
    'Residual over 1 px, scattered: the film is out of focus for the camera, or the exposure is'
    'clipping. Refocus, drop exposure until no red saturation pixels remain, recapture dark, retake.'
    'Residual over 1 px concentrated in a few points: those spots probably fell outside the'
    'illuminated patch, where the Gaussian is dim. Reduce the grid extent and retake.'
    'Scale off by a few percent: read the "What invalidates the calibration" table in CLAUDE.md.'
    'The periscope order is the highest-leverage single item - reversed, it moves scale by 0.562x.'};
s.records  = {'Fitted um/px on both axes, compared against handoff 2.3040 groove / 2.6528 dispersion'
              'Residual (camera px)'};
s.plot     = 'residuals';
steps(end+1) = s;

s          = newStep('lateral_scan_camera', '4b', 'ScanImage field to camera');
