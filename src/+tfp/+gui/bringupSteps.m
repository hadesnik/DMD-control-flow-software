% ===========================================================================
% Builders. Local so the registry above reads as a table rather than as
% struct() calls with cell-wrapping noise.
% ===========================================================================

function s = emptyStep()
%emptyStep A 0x0 struct array with exactly the step fields, so appending is
%   always shape-safe and a typo in a field name fails loudly.
s = struct('id', {}, 'section', {}, 'title', {}, 'purpose', {}, 'kind', {}, ...
    'requires', {}, 'needs', {}, 'setup', {}, 'willDo', {}, 'hazard', {}, ...
    'checks', {}, 'method', {}, 'knobs', {}, 'saveKind', {}, 'criteria', {}, ...
    'remedy', {}, 'records', {}, 'plot', {});
end

function s = newStep(id, section, title)
s = struct('id', id, 'section', section, 'title', title, 'purpose', '', ...
    'kind', 'measure', 'requires', {{}}, 'needs', {{}}, 'setup', {{}}, ...
    'willDo', {{}}, 'hazard', '', 'checks', {{}}, 'method', '', ...
    'knobs', emptyKnob(), 'saveKind', '', 'criteria', emptyCrit(), ...
    'remedy', {{}}, 'records', {{}}, 'plot', 'none');
end

function k = emptyKnob()
k = struct('name', {}, 'label', {}, 'default', {}, 'unit', {}, 'hint', {});
end

function k = knob(name, label, default, unit, hint)
%knob One operator-settable option for a step.
k = struct('name', name, 'label', label, 'default', default, ...
    'unit', unit, 'hint', hint);
end

function c = emptyCrit()
c = struct('field', {}, 'label', {}, 'unit', {}, 'test', {}, 'value', {}, ...
    'severity', {}, 'why', {});
end

function c = crit(field, label, unit, test, value, severity, why)
%crit One acceptance test on a step's result.
%
%   field    dotted path into the result struct; a leading 'm.' reaches the
%            derived metrics from tfp.gui.stepMetrics.
%   test     'lt' | 'gt' | 'le' | 'ge' | 'eq' | 'isTrue' | 'isFalse'
%   severity 'fail'   the measurement did not work - retake it
%            'adjust' something PHYSICAL is wrong - change it, then retake
%            'warn'   outside a design band, but the measurement is the truth
%            'info'   reported, never gates anything
%   why      one or two sentences, shown next to the number in the report.
c = struct('field', field, 'label', label, 'unit', unit, 'test', test, ...
    'value', value, 'severity', severity, 'why', why);
end
